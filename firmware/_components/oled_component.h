// Minimal self-contained SSD1306 128x64 I2C driver (ESP-IDF v5.x i2c_master API).
// Used to show gesture prompts during data collection. Non-fatal: if the OLED
// isn't present, oled_init() returns false and the CSI pipeline runs unaffected.
#pragma once
#include <string.h>
#include <ctype.h>
#include "driver/i2c_master.h"
#include "esp_log.h"

#define OLED_SDA   21
#define OLED_SCL   22
#define OLED_ADDR  0x3C
#define OLED_W     128
#define OLED_H     64

static i2c_master_bus_handle_t  s_oled_bus = NULL;
static i2c_master_dev_handle_t  s_oled_dev = NULL;
static uint8_t s_fb[OLED_W * OLED_H / 8];
static bool s_oled_ok = false;

